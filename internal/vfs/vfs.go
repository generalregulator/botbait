var (
	ErrNotExist = errors.New("No such file or directory")
	ErrExist    = errors.New("File exists")
	ErrIsDir    = errors.New("Is a directory")
	ErrNotDir   = errors.New("Not a directory")
	ErrNoSpace  = errors.New("No space left on device")
	ErrNotEmpty = errors.New("Directory not empty")
)

type Origin int

const (
	OriginSeed Origin = iota
	OriginAttacker
	OriginPushed
	OriginSynthetic
)

type Limits struct {
	MaxFileBytes  int64
	MaxTotalBytes int64
	MaxNodes      int
}

var DefaultLimits = Limits{MaxFileBytes: 512 << 10, MaxTotalBytes: 2 << 20, MaxNodes: 512}

type node struct {
	dir    bool
	text   string
	data   []byte
	vsize  int64
	mode   uint32
	mtime  time.Time
	origin Origin
	owner  string

	stubKey string

	loader func() ([]byte, error)
}

func (n *node) size() int64 {
	switch {
	case n.dir:
		return 4096
	case n.data != nil:
		return int64(len(n.data))
	case n.vsize > 0:
		return n.vsize
	}
	return int64(len(n.text))
}

type Base struct {
	nodes    map[string]*node
	children map[string][]string
	home     string
	mtime    time.Time
	elf      elfSpec
}

func NewBase(p *profile.Profile) *Base {
	b := &Base{nodes: map[string]*node{}, children: map[string][]string{}, home: p.Shell.Home,
		mtime: time.Date(2019, 8, 26, 18, 12, 0, 0, time.UTC), elf: elfSpecFor(p)}
	if p.Kind == profile.KindRouter {
		b.mtime = time.Date(2016, 3, 8, 11, 7, 0, 0, time.UTC)
	}
	b.addDir("/", 0o755)
	for _, d := range p.Dirs {
		b.mkdirAll(d)
	}
	for k, v := range p.Files {
		b.addFile(k, v, 0o644)
	}
	for k, v := range p.Proc {
		b.addFile("/proc/"+k, v, 0o444)
	}
	if p.Kind == profile.KindAndroid {
		b.addFile("/system/build.prop", buildProp(p.Props), 0o644)
		for _, name := range p.Bins {
			b.addBin("/system/bin/"+name, name)
		}
		if p.Busybox.Present {
			b.addBin("/system/xbin/busybox", "busybox")
		}
		b.mkdirAll("/data/local/tmp")
	} else {
		for _, name := range p.Bins {
			b.addBin("/bin/"+name, name)
		}
		if p.Busybox.Present && !p.HasBin("busybox") {
			b.addBin("/bin/busybox", "busybox")
		}
	}
	for _, dev := range []string{"null", "zero", "random", "urandom", "tty", "console", "ttyS0"} {
		b.addFile("/dev/"+dev, "", 0o666)
	}
	b.addStub("/proc/self/exe", 0o777, 109568)
	for k := range b.children {
		sort.Strings(b.children[k])
	}
	return b
}

func buildProp(props map[string]string) string {
	keys := make([]string, 0, len(props))
	for k := range props {
		if strings.HasPrefix(k, "ro.") {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	var sb strings.Builder
	sb.WriteString("# begin build properties\n# autogenerated by buildinfo.sh\n")
	for _, k := range keys {
		sb.WriteString(k + "=" + props[k] + "\n")
	}
	return sb.String()
}

func (b *Base) link(p string) {
	if p == "/" {
		return
	}
	dir := path.Dir(p)
	for _, c := range b.children[dir] {
		if c == p {
			return
		}
	}
	b.children[dir] = append(b.children[dir], p)
}

func (b *Base) addDir(p string, mode uint32) {
	if _, ok := b.nodes[p]; ok {
		return
	}
	b.nodes[p] = &node{dir: true, mode: mode, mtime: b.mtime, owner: "root"}
	b.link(p)
}

func (b *Base) mkdirAll(p string) {
	if p == "/" || p == "." {
		return
	}
	b.mkdirAll(path.Dir(p))
	b.addDir(p, 0o755)
}

func (b *Base) addFile(p, text string, mode uint32) {
	b.mkdirAll(path.Dir(p))
	b.nodes[p] = &node{text: text, mode: mode, mtime: b.mtime, owner: "root"}
	b.link(p)
}

func (b *Base) addBin(p, name string) {
	b.mkdirAll(path.Dir(p))

	var h uint32 = 2166136261
	for i := 0; i < len(name); i++ {
		h = (h ^ uint32(name[i])) * 16777619
	}
	b.nodes[p] = &node{vsize: int64(8192 + h%131072), mode: 0o755, mtime: b.mtime, owner: "root", stubKey: p}
	b.link(p)
}

func (b *Base) addStub(p string, mode uint32, size int64) {
	b.mkdirAll(path.Dir(p))
	b.nodes[p] = &node{vsize: size, mode: mode, mtime: b.mtime, owner: "root", stubKey: p}
	b.link(p)
}

type Created struct {
	Path   string
	Data   []byte
	Mode   uint32
	Pushed bool
	Size   int64
}

type Info struct {
	Path   string
	Name   string
	IsDir  bool
	Size   int64
	Mode   uint32
	MTime  time.Time
	Owner  string
	Origin Origin
}

type FS struct {
	mu      sync.Mutex
	base    *Base
	over    map[string]*node
	deleted map[string]bool
	lim     Limits
	used    int64
	newN    int
	archive []Created
	dyn     map[string]func() string
	now     func() time.Time
}

func (b *Base) New(lim Limits) *FS {
	return &FS{base: b, over: map[string]*node{}, deleted: map[string]bool{}, lim: lim,
		dyn: map[string]func() string{}, now: time.Now}
}

func (b *Base) Home() string { return b.home }

func (f *FS) SetDynamic(p string, gen func() string) {
	f.mu.Lock()
	f.dyn[p] = gen
	f.mu.Unlock()
}

func Clean(cwd, p string) string {
	if p == "" {
		return cwd
	}
	if !strings.HasPrefix(p, "/") {
		p = cwd + "/" + p
	}
	return path.Clean(p)
}

func (f *FS) get(p string) (*node, bool) {
	if n, ok := f.over[p]; ok {
		return n, true
	}
	if f.deleted[p] {
		return nil, false
	}
	n, ok := f.base.nodes[p]
	return n, ok
}

func discard(p string) bool {
	return strings.HasPrefix(p, "/proc/") || strings.HasPrefix(p, "/sys/") || strings.HasPrefix(p, "/dev/")
}

func (f *FS) Stat(p string) (Info, bool) {
	f.mu.Lock()
	defer f.mu.Unlock()
	n, ok := f.get(p)
	if !ok {
		if _, d := f.dyn[p]; d {
			return Info{Path: p, Name: path.Base(p), Mode: 0o444, MTime: f.now(), Owner: "root"}, true
		}
		return Info{}, false
	}
	return infoOf(p, n), true
}

func infoOf(p string, n *node) Info {
	return Info{Path: p, Name: path.Base(p), IsDir: n.dir, Size: n.size(), Mode: n.mode, MTime: n.mtime,
		Owner: n.owner, Origin: n.origin}
}

func (f *FS) ReadFile(p string) ([]byte, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if gen, ok := f.dyn[p]; ok {
		return []byte(gen()), nil
	}
	n, ok := f.get(p)
	if !ok {
		return nil, ErrNotExist
	}
	if n.dir {
		return nil, ErrIsDir
	}
	if n.data != nil {
		return append([]byte(nil), n.data...), nil
	}
	if n.loader != nil {
		return n.loader()
	}
	if n.stubKey != "" {
		return f.base.elf.image(n.stubKey, n.vsize), nil
	}
	return []byte(n.text), nil
}

func (f *FS) List(p string) ([]Info, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	n, ok := f.get(p)
	if !ok {
		return nil, ErrNotExist
	}
	if !n.dir {
		return []Info{infoOf(p, n)}, nil
	}
	seen := map[string]bool{}
	var out []Info
	add := func(c string) {
		if seen[c] {
			return
		}
		seen[c] = true
		if cn, ok := f.get(c); ok {
			out = append(out, infoOf(c, cn))
		}
	}
	for _, c := range f.base.children[p] {
		add(c)
	}
	for c := range f.over {
		if c != "/" && path.Dir(c) == p {
			add(c)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func (f *FS) Mkdir(p string, parents bool) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	return f.mkdirLocked(p, parents)
}

func (f *FS) mkdirLocked(p string, parents bool) error {
	if n, ok := f.get(p); ok {
		if parents && n.dir {
			return nil
		}
		return ErrExist
	}
	parent := path.Dir(p)
	if pn, ok := f.get(parent); !ok {
		if !parents {
			return ErrNotExist
		}
		if err := f.mkdirLocked(parent, true); err != nil {
			return err
		}
	} else if !pn.dir {
		return ErrNotDir
	}
	if f.newN >= f.lim.MaxNodes {
		return ErrNoSpace
	}
	f.newN++
	delete(f.deleted, p)
	f.over[p] = &node{dir: true, mode: 0o755, mtime: f.now(), owner: "root", origin: OriginAttacker}
	return nil
}

func (f *FS) WriteFile(p string, data []byte, appendMode bool) error {
	return f.write(p, data, appendMode)
}

func (f *FS) WriteSynthetic(p string, size int64) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.parentOK(p); err != nil {
		return err
	}
	if n, ok := f.get(p); ok && n.dir {
		return ErrIsDir
	}
	f.over[p] = &node{vsize: size, mode: 0o644, mtime: f.now(), owner: "root", origin: OriginSynthetic}
	delete(f.deleted, p)
	return nil
}

func (f *FS) AddPushed(p string, mode uint32, size int64, load func() ([]byte, error)) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	if err := f.parentOK(p); err != nil {
		return err
	}
	if f.newN >= f.lim.MaxNodes {
		return ErrNoSpace
	}
	if _, ok := f.get(p); !ok {
		f.newN++
	}
	f.over[p] = &node{vsize: size, mode: mode, mtime: f.now(), owner: "root", origin: OriginPushed, loader: load}
	delete(f.deleted, p)
	return nil
}

func (f *FS) parentOK(p string) error {
	pn, ok := f.get(path.Dir(p))
	if !ok {
		return ErrNotExist
	}
	if !pn.dir {
		return ErrNotDir
	}
	return nil
}

func (f *FS) write(p string, data []byte, appendMode bool) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	if discard(p) {
		return nil
	}
	if err := f.parentOK(p); err != nil {
		return err
	}
	n, exists := f.get(p)
	if exists && n.dir {
		return ErrIsDir
	}

	var prev []byte
	origin, mode := OriginAttacker, uint32(0o644)
	if exists {
		mode = n.mode
		switch n.origin {
		case OriginSeed:

			origin = OriginSeed
			if appendMode {
				if n.data != nil {
					prev = n.data
				} else {
					prev = []byte(n.text)
				}
			}
		case OriginAttacker:
			if appendMode {
				prev = n.data
			} else {
				f.archiveLocked(p, n.data, n.mode)
			}
		}
	}

	if int64(len(prev))+int64(len(data)) > f.lim.MaxFileBytes || f.used+int64(len(data)) > f.lim.MaxTotalBytes {
		return ErrNoSpace
	}
	if !exists {
		if f.newN >= f.lim.MaxNodes {
			return ErrNoSpace
		}
		f.newN++
	}
	merged := make([]byte, 0, len(prev)+len(data))
	merged = append(merged, prev...)
	merged = append(merged, data...)
	f.used += int64(len(data))
	delete(f.deleted, p)
	f.over[p] = &node{data: merged, mode: mode, mtime: f.now(), owner: "root", origin: origin}
	return nil
}

const maxArchive = 16

func (f *FS) isDeviceImageLocked(data []byte) bool {
	for _, n := range f.base.nodes {
		if n.stubKey != "" && n.vsize == int64(len(data)) && bytes.Equal(f.base.elf.image(n.stubKey, n.vsize), data) {
			return true
		}
	}
	return false
}

func (f *FS) archiveLocked(p string, data []byte, mode uint32) {
	if len(data) == 0 || len(f.archive) >= maxArchive || f.isDeviceImageLocked(data) {
		return
	}
	f.archive = append(f.archive, Created{Path: p, Data: append([]byte(nil), data...), Mode: mode})
}

func (f *FS) Remove(p string, recursive bool) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	n, ok := f.get(p)
	if !ok {
		return ErrNotExist
	}
	if discard(p) {
		return nil
	}
	if n.dir {
		kids := f.childrenLocked(p)
		if len(kids) > 0 && !recursive {
			return ErrNotEmpty
		}
		for _, c := range kids {
			_ = f.removeLocked(c)
		}
	}
	return f.removeLocked(p)
}

func (f *FS) childrenLocked(p string) []string {
	seen := map[string]bool{}
	var out []string
	for _, c := range f.base.children[p] {
		if _, ok := f.get(c); ok && !seen[c] {
			seen[c] = true
			out = append(out, c)
		}
	}
	for c := range f.over {
		if c != "/" && path.Dir(c) == p && !seen[c] {
			seen[c] = true
			out = append(out, c)
		}
	}
	return out
}

func (f *FS) removeLocked(p string) error {
	n, ok := f.get(p)
	if !ok {
		return nil
	}
	if n.dir {
		for _, c := range f.childrenLocked(p) {
			_ = f.removeLocked(c)
		}
	} else if n.origin == OriginAttacker {
		f.archiveLocked(p, n.data, n.mode)
	}
	delete(f.over, p)
	if _, inBase := f.base.nodes[p]; inBase {
		f.deleted[p] = true
	}
	return nil
}

func (f *FS) Rename(src, dst string) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	n, ok := f.get(src)
	if !ok {
		return ErrNotExist
	}
	if dn, ok := f.get(dst); ok && dn.dir && !n.dir {
		dst = path.Join(dst, path.Base(src))
	}
	if err := f.parentOK(dst); err != nil {
		return err
	}
	if n.dir {
		return f.moveTreeLocked(src, dst)
	}
	cp := *n
	f.over[dst] = &cp
	delete(f.deleted, dst)
	delete(f.over, src)
	if _, inBase := f.base.nodes[src]; inBase {
		f.deleted[src] = true
	}
	return nil
}

func (f *FS) moveTreeLocked(src, dst string) error {
	if f.newN >= f.lim.MaxNodes {
		return ErrNoSpace
	}
	n, _ := f.get(src)
	cp := *n
	f.over[dst] = &cp
	delete(f.deleted, dst)
	f.newN++
	for _, c := range f.childrenLocked(src) {
		if err := f.moveTreeLocked(c, path.Join(dst, path.Base(c))); err != nil {
			return err
		}
	}
	delete(f.over, src)
	if _, inBase := f.base.nodes[src]; inBase {
		f.deleted[src] = true
	}
	return nil
}

func (f *FS) Copy(src, dst string) error {
	if info, ok := f.Stat(dst); ok && info.IsDir {
		dst = path.Join(dst, path.Base(src))
	}

	f.mu.Lock()
	if n, ok := f.get(src); ok && !n.dir && n.stubKey != "" && n.data == nil && n.loader == nil {
		defer f.mu.Unlock()
		if err := f.parentOK(dst); err != nil {
			return err
		}
		if d, ok := f.get(dst); ok && d.dir {
			return ErrIsDir
		} else if !ok {
			if f.newN >= f.lim.MaxNodes {
				return ErrNoSpace
			}
			f.newN++
		}
		f.over[dst] = &node{vsize: n.vsize, stubKey: n.stubKey, mode: n.mode, mtime: f.now(), owner: "root", origin: OriginSynthetic}
		delete(f.deleted, dst)
		return nil
	}
	f.mu.Unlock()
	data, err := f.ReadFile(src)
	if err != nil {
		return err
	}
	return f.write(dst, data, false)
}

func (f *FS) Chmod(p string, mode uint32) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	n, ok := f.get(p)
	if !ok {
		return ErrNotExist
	}
	if _, own := f.over[p]; !own {
		cp := *n
		n = &cp
		f.over[p] = n
		delete(f.deleted, p)
	}
	n.mode = mode
	return nil
}

func (f *FS) Created() []Created {
	f.mu.Lock()
	defer f.mu.Unlock()
	var out []Created
	out = append(out, f.archive...)
	paths := make([]string, 0, len(f.over))
	for p := range f.over {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		n := f.over[p]
		switch {
		case n.dir:
		case n.origin == OriginAttacker && len(n.data) > 0 && !f.isDeviceImageLocked(n.data):
			out = append(out, Created{Path: p, Data: append([]byte(nil), n.data...), Mode: n.mode})
		}
	}
	return out
}
